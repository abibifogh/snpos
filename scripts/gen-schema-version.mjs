#!/usr/bin/env node
/**
 * Write the schema's fingerprint where the apps can read it.
 *
 *   npm run gen:schema
 *
 * The apps cannot import scripts/schema.mjs, so the value is generated into
 * packages/core/src/schema-version.ts and committed. `npm run check:writes`
 * fails when the file is stale, so a schema change cannot ship without the
 * apps knowing the database now needs a provision run.
 */
import { writeFileSync } from 'node:fs';
import { COLLECTIONS, FEATURES, SYSTEM_ACCOUNT_CODES, TEAMS, BUCKETS } from './schema.mjs';
import { schemaFingerprint } from './schema-fingerprint.mjs';

const version = schemaFingerprint({ COLLECTIONS, FEATURES, SYSTEM_ACCOUNT_CODES, TEAMS, BUCKETS });

writeFileSync('packages/core/src/schema-version.ts', `/**
 * GENERATED by scripts/gen-schema-version.mjs. Do not edit; run npm run gen:schema.
 *
 * The shape of the database this build of the apps was written against.
 * Provisioning writes the same value onto the settings row when it finishes;
 * when the row says something else, the database is behind and the apps say
 * so. See scripts/schema-fingerprint.mjs.
 */
export const SCHEMA_VERSION = '${version}';
`);

console.log(`Wrote packages/core/src/schema-version.ts: ${version}`);
